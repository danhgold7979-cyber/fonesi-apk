#!/usr/bin/env python3
"""Generate the reviewed permission overlay for the exact pinned SDK; no code execution."""
import argparse
import hashlib
import os
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile

from fetch_engine_sdk import COMMIT, SHA256

ANDROID = "http://schemas.android.com/apk/res/android"
TOOLS = "http://schemas.android.com/tools"
A, T = "{" + ANDROID + "}", "{" + TOOLS + "}"
ET.register_namespace("android", ANDROID)
ET.register_namespace("tools", TOOLS)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify the checked-in overlay without changing it")
    args = parser.parse_args()
    tools = Path(os.environ.get("FONESI_TOOLS_DIR", "/workspace/.fonesi-tools"))
    sdk = tools / "engine-sdk/spacecore" / COMMIT / "flib-release.aar"
    if hashlib.sha256(sdk.read_bytes()).hexdigest() != SHA256:
        raise RuntimeError("Unverified SDK; refusing to generate overlay")
    with zipfile.ZipFile(sdk) as z:
        source = ET.fromstring(z.read("AndroidManifest.xml"))
    root = ET.Element("manifest")
    internal = "${applicationId}.permission.INTERNAL_SDK"
    ET.SubElement(root, "permission", {A + "name": internal, A + "protectionLevel": "signature"})
    ET.SubElement(root, "uses-permission", {A + "name": internal})
    kept = {
        "android.permission.FOREGROUND_SERVICE", "android.permission.POST_NOTIFICATIONS",
        "android.permission.FOREGROUND_SERVICE_SPECIAL_USE",
    }
    declared = {p.get(A + "name") for p in source.findall("uses-permission")}
    for permission in sorted(declared - kept):
        # Lint scans removal markers as if they requested permissions. These suppressions
        # apply ONLY to removal nodes; verify_probe_apks.py independently rejects any
        # resulting APK permission outside its exact allowlist. No global lint baseline.
        ET.SubElement(root, "uses-permission", {
            A + "name": permission, T + "node": "remove",
            T + "ignore": "ProtectedPermissions,QueryAllPackagesPermission,PermissionImpliesUnsupportedChromeOsHardware,SystemPermissionTypo,ScopedStorage",
        })
    for permission in sorted(kept):
        ET.SubElement(root, "uses-permission", {A + "name": permission})
    queries = ET.SubElement(root, "queries")
    ET.SubElement(queries, "package", {A + "name": "vn.fonesi.payload"})
    app = ET.SubElement(root, "application", {
        A + "name": ".ProbeApplication", A + "label": "Fonesi thử engine",
        A + "allowBackup": "false", A + "fullBackupContent": "false",
        A + "dataExtractionRules": "@xml/probe_data_extraction_rules",
        A + "usesCleartextTraffic": "false", A + "largeHeap": "false",
        A + "permission": internal,
        A + "theme": "@android:style/Theme.Material.Light.NoActionBar",
        T + "replace": "android:usesCleartextTraffic,android:largeHeap",
    })
    # Explicit empty permission overrides the application default for the public launcher only.
    activity = ET.SubElement(app, "activity", {
        A + "name": ".ProbeActivity", A + "exported": "true", A + "permission": "",
    })
    intent = ET.SubElement(activity, "intent-filter")
    ET.SubElement(intent, "action", {A + "name": "android.intent.action.MAIN"})
    ET.SubElement(intent, "category", {A + "name": "android.intent.category.LAUNCHER"})
    for service in [
        "com.fvbox.lib.system.server.DaemonService",
        "com.fvbox.lib.system.server.DaemonService$DaemonInnerService",
    ]:
        item = ET.SubElement(app, "service", {A + "name": service, A + "foregroundServiceType": "specialUse"})
        ET.SubElement(item, "property", {
            A + "name": "android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE",
            A + "value": "Offline synthetic-data engine verification",
        })
    ET.indent(root, space="    ")
    out = Path(__file__).resolve().parents[1] / "engine-probe/src/main/AndroidManifest.xml"
    content = "<!-- Generated by scripts/generate_probe_manifest.py; pinned SDK only. -->\n" + ET.tostring(root, encoding="unicode") + "\n"
    if args.check:
        if not out.exists() or out.read_bytes() != content.encode("utf-8"):
            raise RuntimeError("Manifest overlay differs from reviewed generator; check source changes")
        print("Checked-in probe manifest matches the pinned SDK/generator; no files changed.")
    else:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
        print(f"Generated offline probe overlay: removed {len(declared - kept)} inherited permission names.")


if __name__ == "__main__":
    main()
